// Simple translation function: look up each value in the map, fall back to English
function translateValue(value, langMap) {
  if (typeof value !== 'string') return value;
  // Direct lookup
  if (langMap[value]) return langMap[value];
  // Try looking up without leading/trailing whitespace
  const trimmed = value.trim();
  if (langMap[trimmed]) return langMap[trimmed];
  // Return as-is (English fallback)
  return value;
}

function translateObject(obj, langMap) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) return obj;
  const result = {};
  for (const key of Object.keys(obj)) {
    const value = obj[key];
    if (typeof value === 'string') {
      result[key] = translateValue(value, langMap);
    } else if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      result[key] = translateObject(value, langMap);
    } else {
      result[key] = value;
    }
  }
  return result;
}

