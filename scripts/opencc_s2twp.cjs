function convertString(str) {
  if (typeof str !== 'string' || !str) return str;
  let out = str;
  // Phrases first (longest match first)
  S2T_PHRASES.sort((a,b) => b[0].length - a[0].length);
  for (const [s, t] of S2T_PHRASES) if (out.indexOf(s) !== -1) out = out.split(s).join(t);
  // Then char-level
  let chars = '';
  for (let i = 0; i < out.length; i++) {
    const code = out.charCodeAt(i);
    const mapped = S2T_CHARS.get(code);
    chars += mapped ? mapped : out.charAt(i);
  }
  return chars;
}

function walkConvert(value) {
  if (value == null) return value;
  if (typeof value === 'string') return convertString(value);
  if (Array.isArray(value)) return value.map(walkConvert);
  if (typeof value === 'object') {
    const o = {};
    for (const k of Object.keys(value)) o[k] = walkConvert(value[k]);
    return o;
  }
  return value;
}

// ---------------------------------------------------------------------------
// 3. Check (remaining simplified chars in the *output* traditional file)
// ---------------------------------------------------------------------------
// A char is "simplified-only residue" iff it appears as a KEY of S2T_CHARS
// AND its mapped Traditional form is NOT equal to itself.
// We intentionally exclude:
//   - chars that are identical in simplified / traditional form (e.g. 你, 什, 部,
//     功, 夫, 班, etc.). We never flagged these — our mapping just skipped them.
//   - chars whose simplified glyph happens to coincide with an older traditional
//     variant that's still acceptable TW usage (very rare).
function buildSimplifiedOnlySet() {
  // Contextual exclusions — chars whose "simplified" glyph is ALSO a valid,
  // widespread Traditional Chinese character (different meaning from the T
  // mapping, but legitimate 繁 all the same).
  //   才: modern 繁 uses 才 for "talent / only then"; 纔 is dated.
  //   冬: 鼕 = onomatopoeia of drums; 冬 = winter, and is universally used.
  //   板: 闆 = "boss" slang; 板 = board / slab (universal in 石膏板/擺板/板層).
  //   谷: 穀 = grains; 谷 = valley / surname (鬼谷子 is always 谷).
  //   里: 裡/裏 = within; 里 = village / mile / inside — widely accepted TW/HK 繁.
  //   干: 幹/乾 depend entirely on context; 干 is acceptable in thousands of
  //       compounds (天干, 若干, 干涉…). Never flag as simplified-only.
  const CONTEXTUAL_EXCLUDE = new Set(['才', '冬', '板', '谷', '里', '干']);
  const set = new Set();
  for (const [code, mapped] of S2T_CHARS.entries()) {
    const original = String.fromCharCode(code);
    if (CONTEXTUAL_EXCLUDE.has(original)) continue;
    if (mapped && mapped !== original) set.add(original);
  }
  return set;
}

function checkFile(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const simplified = buildSimplifiedOnlySet();
  const lines = raw.split('\n');
  const issues = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    for (let j = 0; j < line.length; j++) {
      const ch = line.charAt(j);
      if (simplified.has(ch)) {
        issues.push(`${file}:${i+1}:${j+1}  found simplified char "${ch}"  context="${line.slice(Math.max(0,j-20), j+21)}"`);
        if (issues.length >= 50) return issues;
      }
    }
  }
  return issues;
}

