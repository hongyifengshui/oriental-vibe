// 4. CLI
// ---------------------------------------------------------------------------
function usage() {
  console.error('Usage:\n  node scripts/opencc_s2twp.cjs convert <input.json> <output.json>\n  node scripts/opencc_s2twp.cjs check   <input.json>');
  process.exit(2);
}
const [cmd, ...args] = process.argv.slice(2);
if (cmd === 'convert') {
  const [inFile, outFile] = args;
  if (!inFile || !outFile) usage();
  const absIn = path.resolve(inFile);
  const absOut = path.resolve(outFile);
  const json = JSON.parse(fs.readFileSync(absIn, 'utf8'));
  const converted = walkConvert(json);
  fs.writeFileSync(absOut, JSON.stringify(converted, null, 2) + '\n', 'utf8');
  const report = checkFile(absOut);
  console.log(`✅ convert  ${absIn}  →  ${absOut}`);
  if (report.length) {
    console.warn(`⚠️  ${report.length} simplified residues found in output (first ${Math.min(10, report.length)}):`);
    console.warn(report.slice(0,10).join('\n'));
    process.exit(1);
  }
  console.log('✅ no simplified residues in output');
} else if (cmd === 'check') {
  const [inFile] = args;
  if (!inFile) usage();
  const issues = checkFile(path.resolve(inFile));
  if (!issues.length) { console.log('✅ check passed'); process.exit(0); }
  console.error(`❌ check failed — ${issues.length} issues (first 20):\n` + issues.slice(0,20).join('\n'));
  process.exit(1);
} else {
  usage();
}
